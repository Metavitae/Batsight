"""Kithe intro sounds: cut the two pings from the founder's chosen file and check the whole intro mix.

  .venv/bin/python tools/intro_sounds.py <8_warp_hyper_alternating.wav> [--mix-out <dir>]

Writes app/src/main/assets/intro/sounds.js (the two pings as base64 WAVs, untouched samples) and prints
the peak of every sound the intro plays, using the same gains, pitch steps and filters as intro.html
(WebAudio lowpass with Q = -3.01 dB = flat Butterworth, no bump; the main pings have no filter). With --mix-out it also writes the full 12.8 s intro mix
for both sound choices so the founder can listen on the computer.
"""
import base64, io, json, sys, wave
from pathlib import Path

import numpy as np

SR = 48000
CUTS = {"warp": (0.250, 0.091), "hyper": (0.500, 0.101)}   # start s, length s (pings are 89 / 99 ms)
LIMIT_DB = -20.0          # founder rule: no sound louder than -20 dBFS
LONG_LIMIT_DB = -30.0     # anything longer than 100 ms must be -30 dBFS or quieter

# Same plan as intro.html (kept in step by hand; the page is the source of truth).
END, EYE_T, BAT_FROM = 12.8, 5.2 + 3.525, 5.6
RATES = [0.84, 0.89, 0.94, 1.0]
PING_GAIN, ECHO_GAIN, ECHO_LP = 0.85, 0.28, 9000
ECHO_Q_DB = -3.0103       # WebAudio Q is in dB; -3.01 dB = Butterworth, no peak at the cutoff
MASTER = 0.98             # small headroom so the phone's resampler can't push a peak past -20 dBFS


def read_mono(path):
    w = wave.open(str(path))
    assert w.getframerate() == SR and w.getsampwidth() == 2
    x = np.frombuffer(w.readframes(w.getnframes()), dtype="<i2").reshape(-1, w.getnchannels())
    return x[:, 0]


def wav_bytes(x):
    b = io.BytesIO()
    w = wave.open(b, "wb")
    w.setnchannels(1); w.setsampwidth(2); w.setframerate(SR)
    w.writeframes(x.astype("<i2").tobytes()); w.close()
    return b.getvalue()


def db(x):
    p = np.max(np.abs(x))
    return 20 * np.log10(p) if p > 0 else -999.0


def lowpass(x, fc):
    if fc >= SR / 2:
        return x
    q = 10 ** (ECHO_Q_DB / 20)
    w0 = 2 * np.pi * fc / SR
    al = np.sin(w0) / (2 * q)
    c = np.cos(w0)
    b = np.array([(1 - c) / 2, 1 - c, (1 - c) / 2]) / (1 + al)
    a = np.array([1, -2 * c / (1 + al), (1 - al) / (1 + al)])
    y = np.zeros(len(x) + 400)
    xx = np.concatenate([x, np.zeros(400)])
    for n in range(len(xx)):
        y[n] = b[0] * xx[n] + (b[1] * xx[n - 1] if n else 0) + (b[2] * xx[n - 2] if n > 1 else 0) \
               - (a[1] * y[n - 1] if n else 0) - (a[2] * y[n - 2] if n > 1 else 0)
    return y


def voice(buf, rate, gain, lp):
    f = buf / 32768.0
    if rate != 1.0:
        t = np.arange(0, len(f) - 1, rate)
        f = np.interp(t, np.arange(len(f)), f)
    return lowpass(f, lp) * gain * MASTER


def bat_plan():
    out, t, d = [], EYE_T, 0.13
    while t >= BAT_FROM:
        out.insert(0, t); t -= d; d *= 1.22
    return [(t, 0.35 + 0.65 * (i / (len(out) - 1)) ** 1.3) for i, t in enumerate(out)]


def check(pings, mix_dir=None):
    rows, ok = [], True
    for name, buf in pings.items():
        mix = np.zeros(int((END + 0.5) * SR))
        sounds = [("ping", 1.0, PING_GAIN, 20000)] + [(f"echo {k+1}", r, ECHO_GAIN, ECHO_LP) for k, r in enumerate(RATES)]
        sounds += [(f"bat {i+1} at {t:.2f}s", 1.0, g, 20000) for i, (t, g) in enumerate(bat_plan())]
        for label, rate, gain, lp in sounds:
            v = voice(buf, rate, gain, lp)
            audible = np.flatnonzero(np.abs(v) > 10 ** (-60 / 20))
            ms = (audible[-1] - audible[0]) / SR * 1000 if len(audible) else 0
            pk = db(v)
            good = pk <= LIMIT_DB and (ms <= 100 or pk <= LONG_LIMIT_DB)
            ok &= good
            rows.append((name, label, round(pk, 2), round(ms, 1), good))
        if mix_dir:
            # Same timing as one play (seed-free: shapes found 0.83 s apart from 1.08 s).
            for k in range(4):
                s = 1.08 + 0.83 * k
                for at, rate, gain, lp in ((s - 0.55, 1.0, PING_GAIN, 20000), (s, RATES[k], ECHO_GAIN, ECHO_LP)):
                    v = voice(buf, rate, gain, lp); i = int(at * SR); mix[i:i + len(v)] += v
            for t, g in bat_plan():
                v = voice(buf, 1.0, g, 20000); i = int(t * SR); mix[i:i + len(v)] += v
            rows.append((name, "WHOLE MIX", round(db(mix), 2), None, db(mix) <= LIMIT_DB))
            Path(mix_dir).mkdir(parents=True, exist_ok=True)
            (Path(mix_dir) / f"intro_sound_{name}.wav").write_bytes(wav_bytes(np.round(mix * 32767)))
    return rows, ok


def main():
    src = Path(sys.argv[1])
    mix_dir = sys.argv[sys.argv.index("--mix-out") + 1] if "--mix-out" in sys.argv else None
    x = read_mono(src)
    pings = {k: x[int(s * SR):int((s + n) * SR)] for k, (s, n) in CUTS.items()}
    js = "// Generated by tools/intro_sounds.py from the founder's chosen sounds (samples untouched).\n"
    js += "window.INTRO_SOUNDS=" + json.dumps({k: base64.b64encode(wav_bytes(v)).decode() for k, v in pings.items()}) + ";\n"
    out = Path(__file__).resolve().parent.parent / "app/src/main/assets/intro/sounds.js"
    out.write_text(js)
    rows, ok = check(pings, mix_dir)
    for r in rows:
        print("%-6s %-18s peak %7.2f dBFS  %s  %s" % (r[0], r[1], r[2], "" if r[3] is None else f"{r[3]:6.1f} ms", "OK" if r[4] else "OVER THE RULE"))
    print("ALL WITHIN THE FOUNDER'S RULES" if ok else "SOMETHING BREAKS THE RULES")
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
